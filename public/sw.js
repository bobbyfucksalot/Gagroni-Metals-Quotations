// Minimal service worker: keeps the app installable (PWA) but never touches
// pages, RSC payloads or API calls, so deploys and auth state are always fresh.
// Only immutable, hashed build assets are cached.
const CACHE_NAME = 'gagroni-metals-v2';

self.addEventListener('install', () => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE_NAME).map((key) => caches.delete(key))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  // Only hashed, immutable assets. Everything else (HTML, RSC, /api) goes straight to the network.
  if (!url.pathname.startsWith('/_next/static/')) return;

  event.respondWith(
    caches.match(request).then((cached) => {
      if (cached) return cached;
      return fetch(request).then((response) => {
        if (response.ok) {
          const copy = response.clone();
          caches.open(CACHE_NAME).then((cache) => cache.put(request, copy));
        }
        return response;
      });
    })
  );
});
